#!/usr/bin/env python3
"""Compose the small, closed saved-board module graph into stable runtime assets.

The Python asset allowlist can remain loaded across a source-only maintenance
pass. Renderers are pure named functions; their only external dependency is the
existing board-client.js contract. This is deliberately not a general bundler.
"""

import argparse
from pathlib import Path
import re
import json
from hashlib import sha256

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "app/dashboard/opportunity_static/current"
JAVASCRIPT = (
    "board-elements.js",
    "comparison-coverage.js",
    "comparison-slate-views.js",
    "stored-views.js",
    "stored-details.js",
    "stored-controller.js",
    "scanner-client.js",
    "scanner-controller.js",
)
STYLES = (
    "stored-shell.css",
    "stored-boards.css",
    "stored-details.css",
    "stored-responsive.css",
    "scanner-style.css",
)
SCANNER_JAVASCRIPT = ("scanner-client.js", "ticket-client.js", "ticket-view.js", "scanner-arrivals.js", "scanner-summaries.js", "scanner-controller.js")
CLIENT_NAMES = (
    "defaults",
    "numeric",
    "money",
    "percent",
    "quantity",
    "settings",
    "checkBoard",
    "checkSlate",
    "SlateAccumulator",
    "readSlate",
    "checkDetails",
    "checkInputs",
    "LatestRead",
    "SavedReadPoller",
    "followGame",
)


def compose_javascript():
    parts = [
        "// Generated by scripts/build_stored_frontend.py; edit the named source modules.\n",
        "import {" + ", ".join(CLIENT_NAMES) + '} from "./board-client.js";\n',
    ]
    allowed = {"./board-client.js", *("./" + name for name in JAVASCRIPT)}
    for name in JAVASCRIPT:
        if name.startswith("scanner-"):
            continue
        source = (ASSETS / name).read_text()
        imports = re.findall(r"(?m)^import\s+[^;]+;", source)
        for statement in imports:
            match = re.search(r"from\s+['\"]([^'\"]+)['\"]", statement)
            if not match or match[1] not in allowed:
                raise ValueError("Unsupported saved-board import in " + name)
            named = re.search(r"import\s+\{([^}]+)\}\s+from", statement)
            names = (
                [part.strip() for part in named[1].split(",") if part.strip()]
                if named
                else []
            )
            if not names or any(
                not re.fullmatch(r"[A-Za-z_$][\w$]*", value) for value in names
            ):
                raise ValueError(
                    "Only unaliased named imports are supported in " + name
                )
            if match[1] == "./board-client.js" and not set(names).issubset(
                CLIENT_NAMES
            ):
                raise ValueError("Update CLIENT_NAMES for " + name)

        source = re.sub(r"(?m)^import\s+[^;]+;\n?", "", source)
        source = re.sub(r"(?m)^export\s+\{[^}]*\};\n?", "", source)
        source = re.sub(r"(?m)^export (?=const |function )", "", source)
        if re.search(r"(?m)^(import|export)\s", source):
            raise ValueError("Unsupported saved-board module form in " + name)
        parts.append("\n// Source: " + name + "\n" + source)
    return "".join(parts)


def outputs():
    scanner_sources = [(ASSETS / n).read_text() for n in SCANNER_JAVASCRIPT]
    shell = (ASSETS / "scanner-shell.html").read_text()
    style = (ASSETS / "scanner-style.css").read_text()
    revision = sha256((shell + style + "".join(scanner_sources)).encode()).hexdigest()
    js = "// Generated by scripts/build_stored_frontend.py.\nconst SCANNER_ASSET_REVISION = " + json.dumps(revision) + ";\n"
    js += 'import { money, quantity, percent, numeric } from "./board-client.js";\n'
    for source in scanner_sources:
        source = re.sub(r"(?m)^import\s+[^;]+;\n?", "", source)
        js += re.sub(r"(?m)^export (?=const |function |async function )", "", source) + "\n"
    scanner = {"scanner.js": js, "scanner.css": style, "scanner.html": shell.replace("__SCANNER_ASSET_REVISION__", revision)}
    scanner["scanner-runtime.json"] = json.dumps(dict(protocol="predict-opportunity-scanner-1", asset_revision=revision, assets={k:sha256(v.encode()).hexdigest() for k,v in scanner.items()}), sort_keys=True) + "\n"
    return {
        **scanner,
        "stored.js": compose_javascript(),
        "stored.css": "/* Generated from the named stored-*.css sources; keep their cascade order. */\n"
        + "".join((ASSETS / name).read_text() for name in STYLES if name != "scanner-style.css"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Reject drift without modifying assets"
    )
    check = parser.parse_args().check
    for name, body in outputs().items():
        if check:
            if (ASSETS / name).read_text() != body:
                raise ValueError(
                    "Generated asset drift: "
                    + name
                    + "; run scripts/build_stored_frontend.py"
                )
        else:
            (ASSETS / name).write_text(body)
    print("PASS saved-board asset composition" + (" and drift check" if check else ""))


if __name__ == "__main__":
    main()
