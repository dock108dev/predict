import assert from 'node:assert/strict';
import {DiagnosticSession} from '../app/dashboard/opportunity_static/current/session-history.js';
const s=new DiagnosticSession();s.sources=()=>{};
const p=(decimal,receipt,current=true)=>({offset:0,rows:[{game_title:'Test',offers:[{id:'one',odds:{decimal},received_at:receipt,current}]}]});
s.observe(p('2','a'),{});s.observe(p('2','b'),{});s.observe(p('3','c'),{});s.observe(p('3','c',false),{});s.observe({offset:0,rows:[]},{});
assert(s.events.some(e=>e.kind==='unchanged_price_confirmation'));
assert(s.events.some(e=>e.kind==='material_change'&&e.direction==='decimal_odds_up'));
assert(s.events.some(e=>e.kind==='price_withdrawn'));
assert(s.events.some(e=>e.kind==='left_displayed_population'));
const availability=new DiagnosticSession();availability.sources=()=>{};
const priced=(current,fee,receipt)=>{const page=p('2',receipt,current);Object.assign(page.rows[0].offers[0],{before_fee:fee,after_fee:fee});return page;};
availability.observe(priced(true,'5','first'),{});
availability.observe(priced(false,null,'first'),{});
availability.observe(priced(true,'5','second'),{});
assert.equal(availability.events.filter(e=>e.kind==='calculation_availability_change').length,2);
assert(!availability.events.some(e=>e.kind==='material_change'));
assert(availability.events.some(e=>e.kind==='unchanged_price_confirmation'&&e.received_at==='second'));
availability.observe(priced(true,'6','third'),{});
assert(availability.events.some(e=>e.kind==='material_change'&&e.direction==='unchanged_odds'));
for(let i=0;i<1100;i++)s.record('check');assert.equal(s.events.length,1000);assert(s.dropped>0);
console.log('History checks passed: confirmations, direction, withdrawals, gaps and bounded retention');
