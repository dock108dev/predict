-- Domain current-price catalog; lossless compact facts/revisions, bounded current keys.
CREATE TABLE current_price_game_fact (
 id bytea PRIMARY KEY CHECK(octet_length(id)=32),
 payload bytea NOT NULL, logical_bytes integer NOT NULL CHECK(logical_bytes BETWEEN 1 AND 524288),
 encoding smallint NOT NULL CHECK(encoding IN (0,1))
);
CREATE TABLE current_price_game (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, game_key text NOT NULL UNIQUE, fact_id bytea NOT NULL REFERENCES current_price_game_fact(id),
 received_order numeric NOT NULL
);
CREATE TABLE current_price_revision (
 id bytea PRIMARY KEY CHECK(octet_length(id)=32), game_id bigint NOT NULL REFERENCES current_price_game(id),
 venue text NOT NULL, fact_id bytea NOT NULL REFERENCES current_price_game_fact(id),
 payload bytea NOT NULL, logical_bytes integer NOT NULL CHECK(logical_bytes BETWEEN 1 AND 524288),
 encoding smallint NOT NULL CHECK(encoding IN (0,1))
);
CREATE INDEX current_price_revision_history ON current_price_revision(game_id,venue);
CREATE TABLE current_price_latest (
 game_id bigint NOT NULL REFERENCES current_price_game(id), venue text NOT NULL,
 revision_id bytea NOT NULL REFERENCES current_price_revision(id),
 source_order numeric NOT NULL, received_order numeric NOT NULL,
 PRIMARY KEY(game_id,venue)
);
CREATE FUNCTION reject_current_price_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'immutable current-price fact/revision'; END; $$;
CREATE TRIGGER immutable_current_price_fact BEFORE UPDATE OR DELETE ON current_price_game_fact
 FOR EACH ROW EXECUTE FUNCTION reject_current_price_mutation();
CREATE TRIGGER immutable_current_price_revision BEFORE UPDATE OR DELETE ON current_price_revision
 FOR EACH ROW EXECUTE FUNCTION reject_current_price_mutation();
