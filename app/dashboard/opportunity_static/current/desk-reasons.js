export function evidenceReason(value, fallback = 'The evidence needed for this result is unavailable.') {
  const codes = Array.isArray(value) ? value : String(value || '').split(', ');
  const messages = codes.map(code => Object.hasOwn(reasonLabels, code) ? reasonLabels[code] : null);
  return [...new Set(messages.map(message => message || fallback))].join(' ') || fallback;
}
